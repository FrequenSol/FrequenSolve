#!/usr/bin/env python3
"""Generate standalone Cloud benchmark workloads from tutorial source cells.

The checked-in benchmark scripts are the runtime inputs. This generator is used
only when tutorial source changes; benchmark execution never imports Jupyter or
opens an ``.ipynb`` file.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import shutil
from pathlib import Path
from typing import Any

import black
import isort

CORPUS_SCHEMA = "frequensolve-cloud-benchmark-corpus/v1"
GENERATED_MARKER = ".generated-cloud-benchmark-workloads"
PRESENTATION_IMPORTS = {"IPython", "matplotlib", "pandas"}
PRESENTATION_NAMES = {"Image", "display", "plt", "pd", "fig", "ax", "axes"}
PRESENTATION_METHODS = {
    "plot",
    "render",
    "render_paraview",
    "savefig",
    "show",
}
EXPECTED_SUBMISSION_OVERRIDES = {
    "01_modeling_basics/06_laplace_time_domain": 3,
    "07_performance/01_performance": 9,
}


def _sha256(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


class _Calls(ast.NodeVisitor):
    def __init__(self) -> None:
        self.submit_count = 0
        self.names: set[str] = set()
        self.attributes: set[str] = set()

    def visit_Name(self, node: ast.Name) -> None:
        self.names.add(node.id)

    def visit_Attribute(self, node: ast.Attribute) -> None:
        self.attributes.add(node.attr)
        if node.attr == "submit" and isinstance(node.ctx, ast.Load):
            self.submit_count += 1
        self.generic_visit(node)


def _presentation_only(statement: ast.stmt) -> bool:
    if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Name):
        return True
    if isinstance(statement, (ast.Import, ast.ImportFrom)):
        modules = []
        if isinstance(statement, ast.Import):
            modules = [alias.name.split(".")[0] for alias in statement.names]
        elif statement.module:
            modules = [statement.module.split(".")[0]]
        return bool(PRESENTATION_IMPORTS.intersection(modules))
    calls = _Calls()
    calls.visit(statement)
    if calls.submit_count:
        return False
    return bool(
        calls.names.intersection(PRESENTATION_NAMES)
        or calls.attributes.intersection(PRESENTATION_METHODS)
        or (
            isinstance(statement, ast.Expr)
            and isinstance(statement.value, ast.Attribute)
            and statement.value.attr == "executable"
        )
    )


def _cell_source(cell: dict[str, Any], source: Path, index: int) -> str:
    source_text = "".join(cell.get("source", []))
    try:
        tree = ast.parse(source_text, filename=f"{source}:cell-{index}")
    except SyntaxError as error:
        raise RuntimeError(
            f"Tutorial cell is not standalone Python: {source}:{index}"
        ) from error
    tree.body = [
        statement for statement in tree.body if not _presentation_only(statement)
    ]
    ast.fix_missing_locations(tree)
    return ast.unparse(tree).strip()


def _submission_count(notebook: dict[str, Any]) -> int:
    count = 0
    for cell in notebook.get("cells", []):
        if cell.get("cell_type") != "code":
            continue
        tree = ast.parse("".join(cell.get("source", [])))
        calls = _Calls()
        calls.visit(tree)
        count += calls.submit_count
    return count


def generate(source_root: Path, output_root: Path) -> dict[str, Any]:
    if output_root.is_symlink():
        raise RuntimeError("Refusing to replace a symlinked benchmark output directory")
    source_root = source_root.resolve()
    output_root = output_root.resolve()
    if output_root.exists():
        if not (output_root / GENERATED_MARKER).is_file():
            raise RuntimeError(
                f"Refusing to replace unmarked benchmark output directory: {output_root}"
            )
        shutil.rmtree(output_root)
    output_root.mkdir(parents=True)
    (output_root / GENERATED_MARKER).write_text(
        "Generated by scripts/generate_cloud_benchmark_workloads.py. "
        "Do not edit files in this directory by hand.\n",
        encoding="utf-8",
    )
    cases = []
    for source in sorted(source_root.rglob("*.ipynb")):
        notebook_bytes = source.read_bytes()
        notebook = json.loads(notebook_bytes)
        relative = source.relative_to(source_root)
        case_id = relative.with_suffix("").as_posix()
        script_relative = relative.with_suffix(".py")
        script = output_root / script_relative
        chunks = [
            '"""Generated Cloud benchmark workload.',
            "",
            f"Source tutorial: {relative.as_posix()}",
            f"Source SHA-256: {_sha256(notebook_bytes)}",
            '"""',
            "",
        ]
        for index, cell in enumerate(notebook.get("cells", [])):
            if cell.get("cell_type") != "code":
                continue
            transformed = _cell_source(cell, source, index)
            if transformed:
                chunks.extend([f"# %% source cell {index}", transformed, ""])
        payload = "\n".join(chunks).rstrip() + "\n"
        payload = isort.code(payload, profile="black")
        try:
            payload = black.format_file_contents(payload, fast=True, mode=black.Mode())
        except black.NothingChanged:
            pass
        compile(payload, str(script), "exec")
        script.parent.mkdir(parents=True, exist_ok=True)
        script.write_text(payload, encoding="utf-8")
        cases.append(
            {
                "id": case_id,
                "source": relative.as_posix(),
                "sourceSha256": _sha256(notebook_bytes),
                "script": script_relative.as_posix(),
                "scriptSha256": _sha256(payload.encode()),
                "expectedSubmissions": EXPECTED_SUBMISSION_OVERRIDES.get(
                    case_id, _submission_count(notebook)
                ),
            }
        )
    manifest = {
        "schema": CORPUS_SCHEMA,
        "generator": "scripts/generate_cloud_benchmark_workloads.py",
        "cases": cases,
        "caseCount": len(cases),
        "submissionCount": sum(case["expectedSubmissions"] for case in cases),
    }
    (output_root / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--source",
        type=Path,
        default=Path("examples/tutorials"),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("benchmarks/cloud/workloads"),
    )
    args = parser.parse_args()
    manifest = generate(args.source, args.output)
    print(json.dumps(manifest, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
